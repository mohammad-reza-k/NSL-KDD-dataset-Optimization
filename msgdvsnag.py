train_df = pd.read_csv('KDDTrain.txt', names=columns)
test_df = pd.read_csv('KDDTest.txt', names=columns)

train_df.drop(columns=['difficulty'], inplace=True)
test_df.drop(columns=['difficulty'], inplace=True)

train_df['label'] = train_df['label'].apply(lambda x: 0 if x == 'normal' else 1)
test_df['label'] = test_df['label'].apply(lambda x: 0 if x == 'normal' else 1)

if 'num_outbound_cmds' in train_df.columns:
    train_df.drop(columns=['num_outbound_cmds'], inplace=True)
    test_df.drop(columns=['num_outbound_cmds'], inplace=True)



categorical_cols = ['protocol_type', 'service', 'flag']
train_df = pd.get_dummies(train_df, columns=categorical_cols)
test_df = pd.get_dummies(test_df, columns=categorical_cols)

merged_train = train_df.copy()
merged_test = test_df.copy()

all_columns = set(merged_train.columns) | set(merged_test.columns)
for col in all_columns:
    if col not in merged_train.columns:
        merged_train[col] = 0
    if col not in merged_test.columns:
        merged_test[col] = 0

merged_train = merged_train[sorted(all_columns)]
merged_test = merged_test[sorted(all_columns)]

X_cols = [col for col in merged_train.columns if col != 'label']
X_full = pd.concat([merged_train[X_cols], merged_test[X_cols]], axis=0)
y_full = pd.concat([merged_train['label'], merged_test['label']], axis=0)


from sklearn.utils import shuffle
X_full, y_full = shuffle(X_full, y_full, random_state=42)

X_train, X_test, y_train, y_test = train_test_split(
    X_full, y_full, test_size=0.2, random_state=42, stratify=y_full
)

scaler = StandardScaler()
X_train = scaler.fit_transform(X_train.astype(np.float32))
X_test = scaler.transform(X_test.astype(np.float32))

def create_model():
    model = Sequential([
        Dense(32, activation='relu', input_shape=(X_train.shape[1],)),
        BatchNormalization(),
        Dense(16, activation='relu'),
        BatchNormalization(),
        Dense(1, activation='sigmoid')
    ])
    return model

print("Momentum SGD")


model_mom = create_model()
opt_mom = SGD(learning_rate=0.001, momentum=0.9, nesterov=False)
model_mom.compile(optimizer=opt_mom, loss='binary_crossentropy', metrics=['accuracy'])

early_stop = EarlyStopping(monitor='val_loss', patience=10, restore_best_weights=True)

history_mom = model_mom.fit(
    X_train, y_train,
    epochs=10,
    batch_size=64,
    validation_split=0.2,
    verbose=1,
    callbacks=[early_stop]
)

print("NAG (Nesterov)")

model_nag = create_model()
opt_nag = SGD(learning_rate=0.001, momentum=0.9, nesterov=True)
model_nag.compile(optimizer=opt_nag, loss='binary_crossentropy', metrics=['accuracy'])

history_nag = model_nag.fit(
    X_train, y_train,
    epochs=10,
    batch_size=64,
    validation_split=0.2,
    verbose=1,
    callbacks=[early_stop]
)


loss_mom, acc_mom = model_mom.evaluate(X_test, y_test, verbose=0)
loss_nag, acc_nag = model_nag.evaluate(X_test, y_test, verbose=0)

y_pred_mom = (model_mom.predict(X_test) > 0.5).astype(int)

y_pred_nag = (model_nag.predict(X_test) > 0.5).astype(int)


